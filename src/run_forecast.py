from __future__ import annotations

from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

from src.forecasting import (
    ALPHA_CANDIDATES,
    BOOTSTRAP_BLOCK_MONTHS,
    BOOTSTRAP_REPLICATES,
    BOOTSTRAP_SEED,
    LAG_MONTHS,
    MODEL_FEATURES,
    VALIDATION_MONTHS,
    VALIDATION_SPLITS,
    build_forecasting_model,
    load_monthly_series,
    make_feature_table,
    monthly_mean_forecast,
    moving_block_bootstrap_mae_difference,
    score_forecast,
    select_ridge_alpha,
    split_by_time,
)


PROJECT_FOLDER = Path(__file__).resolve().parents[1]
DATA_FILE = PROJECT_FOLDER / "data" / "elnino_monthly.csv"
FIGURES_FOLDER = PROJECT_FOLDER / "figures"
RESULTS_FOLDER = PROJECT_FOLDER / "results"


def save_series_plot(series: pd.Series, first_test_month: pd.Timestamp) -> None:
    FIGURES_FOLDER.mkdir(parents=True, exist_ok=True)
    figure, axis = plt.subplots(figsize=(11, 5))
    axis.plot(series.index, series.values, linewidth=1.2)
    axis.axvline(
        first_test_month,
        linestyle="--",
        linewidth=1.4,
        label=f"Test period begins: {first_test_month:%b %Y}",
    )
    axis.set_title("Monthly sea-surface temperature — Niño 1+2")
    axis.set_xlabel("Date")
    axis.set_ylabel("Sea-surface temperature (°C)")
    axis.legend(frameon=False)
    figure.tight_layout()
    figure.savefig(FIGURES_FOLDER / "series_and_split.png", dpi=160)
    plt.close(figure)


def save_forecast_plot(
    observed: pd.Series,
    forecasts: dict[str, pd.Series],
) -> None:
    FIGURES_FOLDER.mkdir(parents=True, exist_ok=True)
    figure, axis = plt.subplots(figsize=(12, 6))
    axis.plot(observed.index, observed.values, label="Observed", linewidth=1.7)
    for label, values in forecasts.items():
        axis.plot(values.index, values.values, label=label, linewidth=1.0)
    axis.set_title("One-step-ahead forecasts using observed history")
    axis.set_xlabel("Date")
    axis.set_ylabel("Sea-surface temperature (°C)")
    axis.legend(frameon=False, ncol=2)
    figure.tight_layout()
    figure.savefig(FIGURES_FOLDER / "test_forecasts.png", dpi=160)
    plt.close(figure)


def save_metric_plot(metrics: pd.DataFrame) -> None:
    FIGURES_FOLDER.mkdir(parents=True, exist_ok=True)
    chart_data = metrics.sort_values("MAE_C", ascending=True)
    figure, axis = plt.subplots(figsize=(9, 5))
    bars = axis.barh(chart_data["Model"], chart_data["MAE_C"])
    axis.set_title("Mean absolute error across the four methods")
    axis.set_xlabel("Mean absolute error (°C) — lower is better")
    axis.set_ylabel("Forecast method")
    axis.set_xlim(0, float(chart_data["MAE_C"].max()) * 1.14)
    axis.bar_label(bars, fmt="%.3f", padding=5)
    axis.invert_yaxis()
    figure.tight_layout()
    figure.savefig(FIGURES_FOLDER / "model_mae_comparison.png", dpi=160)
    plt.close(figure)


def write_experiment_notes(
    series: pd.Series,
    training_data: pd.DataFrame,
    test_data: pd.DataFrame,
    metrics: pd.DataFrame,
    uncertainty: pd.DataFrame,
    selected_alpha: float,
) -> None:
    lines = [
        "# Experiment notes",
        "",
        "These results are regenerated by `python -m src.run_forecast`.",
        "",
        "## Dataset and split",
        "",
        f"The dataset contains {len(series)} monthly observations, from {series.index.min():%B %Y} through {series.index.max():%B %Y}.",
        f"After creating the 12-month lag, {len(training_data)} months were used for training and {len(test_data)} months for final testing.",
        f"The training period is {training_data.index.min():%B %Y} to {training_data.index.max():%B %Y}; the test period is {test_data.index.min():%B %Y} to {test_data.index.max():%B %Y}.",
        "",
        "## Forecast methods",
        "",
        "- **Persistence baseline:** previous month's observed value.",
        "- **Seasonal naive baseline:** observed value from 12 months earlier.",
        "- **Training monthly mean:** average for the target calendar month, calculated using training years only.",
        f"- **Ridge regression:** lags {', '.join(map(str, LAG_MONTHS))} plus calendar sine/cosine features; alpha selected by {VALIDATION_SPLITS}-split time-ordered validation with {VALIDATION_MONTHS}-month validation windows. Selected alpha: `{selected_alpha:g}`.",
        "",
        "The test evaluation uses one-step-ahead forecasts using observed history; no recursive prediction is used. Each test-month forecast can use actual observations that had arrived before that month. Multi-month forecasts made recursively from earlier predictions may be less accurate and require a separate evaluation.",
        "",
        "## Test metrics",
        "",
        "| Model | MAE (°C) | RMSE (°C) |",
        "|---|---:|---:|",
    ]
    for row in metrics.itertuples(index=False):
        lines.append(f"| {row.Model} | {row.MAE_C:.4f} | {row.RMSE_C:.4f} |")

    lines.extend(
        [
            "",
            "## Paired moving-block bootstrap for MAE differences",
            "",
            f"The table reports Ridge MAE minus each baseline's MAE. Negative values favour Ridge. Confidence intervals use a paired circular moving-block bootstrap with {BOOTSTRAP_REPLICATES:,} replicates, {BOOTSTRAP_BLOCK_MONTHS}-month blocks, and seed {BOOTSTRAP_SEED}. The block length preserves short runs of neighbouring monthly errors; the interval is an approximate uncertainty assessment for this test period, not a guarantee of future performance.",
            "",
            "| Comparison | MAE difference (°C) | 95% CI lower | 95% CI upper |",
            "|---|---:|---:|---:|",
        ]
    )
    for row in uncertainty.itertuples(index=False):
        lines.append(
            f"| Ridge minus {row.baseline} | {row.mae_difference_c:.4f} | {row.ci_95_lower_c:.4f} | {row.ci_95_upper_c:.4f} |"
        )

    lines.extend(
        [
            "",
            "## Interpretation and limits",
            "",
            "The test period is a single historical holdout from January 1999 through December 2010. The bootstrap interval describes uncertainty in the paired MAE difference within this holdout. The data cover one region and one forecast horizon; results should not be generalized to other regions, periods, or multi-month recursive forecasts without further testing.",
            "",
            "This is an educational forecasting study, not an operational climate forecast.",
        ]
    )
    RESULTS_FOLDER.mkdir(parents=True, exist_ok=True)
    (RESULTS_FOLDER / "EXPERIMENT_NOTES.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    RESULTS_FOLDER.mkdir(parents=True, exist_ok=True)
    series = load_monthly_series(DATA_FILE)
    feature_table = make_feature_table(series)
    training_data, test_data = split_by_time(feature_table)

    selected_alpha, alpha_results = select_ridge_alpha(training_data)
    alpha_results.to_csv(RESULTS_FOLDER / "alpha_validation.csv", index=False)

    model = build_forecasting_model(selected_alpha)
    model.fit(training_data.loc[:, MODEL_FEATURES], training_data["actual_sst_c"])

    observed = test_data["actual_sst_c"].rename("observed_sst_c")
    forecasts = {
        "Persistence baseline": test_data["persistence_prediction_c"].rename("persistence_prediction_c"),
        "Seasonal naive baseline": test_data["seasonal_naive_prediction_c"].rename("seasonal_naive_prediction_c"),
        "Training monthly mean": monthly_mean_forecast(
            training_data["actual_sst_c"], test_data.index
        ),
        "Ridge regression": pd.Series(
            model.predict(test_data.loc[:, MODEL_FEATURES]),
            index=test_data.index,
            name="ridge_prediction_c",
        ),
    }

    metrics = pd.DataFrame(
        [
            {"Model": name, **score_forecast(observed, prediction)}
            for name, prediction in forecasts.items()
        ]
    )
    metrics.to_csv(RESULTS_FOLDER / "metrics.csv", index=False)

    predictions = pd.concat([observed, *forecasts.values()], axis=1)
    predictions.to_csv(RESULTS_FOLDER / "test_predictions.csv", index_label="date")

    ridge_forecast = forecasts["Ridge regression"]
    baseline_forecasts = {
        name: values
        for name, values in forecasts.items()
        if name != "Ridge regression"
    }
    uncertainty_rows = []
    for name, values in baseline_forecasts.items():
        uncertainty_rows.append(
            {
                "baseline": name,
                **moving_block_bootstrap_mae_difference(
                    observed,
                    ridge_forecast,
                    values,
                ),
            }
        )
    uncertainty = pd.DataFrame(uncertainty_rows)
    uncertainty.to_csv(RESULTS_FOLDER / "mae_difference_bootstrap.csv", index=False)

    save_series_plot(series, test_data.index[0])
    save_forecast_plot(observed, forecasts)
    save_metric_plot(metrics)
    write_experiment_notes(
        series,
        training_data,
        test_data,
        metrics,
        uncertainty,
        selected_alpha,
    )

    print("Forecast comparison finished.\n")
    print(metrics.to_string(index=False, float_format=lambda number: f"{number:.4f}"))
    print(f"\nSelected Ridge alpha: {selected_alpha:g}")
    print("\nRidge minus baseline MAE differences and 95% intervals:")
    print(uncertainty.to_string(index=False, float_format=lambda number: f"{number:.4f}"))
    print(
        f"\nTraining: {training_data.index.min():%Y-%m} "
        f"to {training_data.index.max():%Y-%m}"
    )
    print(
        f"Testing:  {test_data.index.min():%Y-%m} "
        f"to {test_data.index.max():%Y-%m}"
    )
    print("\nUpdated the figures/ and results/ folders.")


if __name__ == "__main__":
    main()
