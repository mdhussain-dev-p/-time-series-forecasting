from __future__ import annotations
from pathlib import Path
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import pandas as pd
from src.forecasting import LAG_MONTHS, MODEL_FEATURES, build_forecasting_model, load_monthly_series, make_feature_table, score_forecast, split_by_time
PROJECT_FOLDER = Path(__file__).resolve().parents[1]
DATA_FILE = PROJECT_FOLDER / 'data' / 'elnino_monthly.csv'
FIGURES_FOLDER = PROJECT_FOLDER / 'figures'
RESULTS_FOLDER = PROJECT_FOLDER / 'results'

def save_series_plot(series: pd.Series, first_test_month: pd.Timestamp) -> None:
    FIGURES_FOLDER.mkdir(parents=True, exist_ok=True)
    figure, axis = plt.subplots(figsize=(11, 5))
    axis.plot(series.index, series.values, linewidth=1.2)
    axis.axvline(first_test_month, linestyle='--', linewidth=1.4, label=f'Test period begins: {first_test_month:%b %Y}')
    axis.set_title('Monthly sea-surface temperature — Niño 1+2')
    axis.set_xlabel('Date')
    axis.set_ylabel('Sea-surface temperature (°C)')
    axis.legend(frameon=False)
    figure.tight_layout()
    figure.savefig(FIGURES_FOLDER / 'series_and_split.png', dpi=160)
    plt.close(figure)

def save_forecast_plot(observed: pd.Series, baseline: pd.Series, ridge_forecast: pd.Series) -> None:
    FIGURES_FOLDER.mkdir(parents=True, exist_ok=True)
    figure, axis = plt.subplots(figsize=(11, 5))
    axis.plot(observed.index, observed.values, label='Observed', linewidth=1.6)
    axis.plot(baseline.index, baseline.values, label='Naive baseline', linewidth=1.1)
    axis.plot(ridge_forecast.index, ridge_forecast.values, label='Ridge regression', linewidth=1.1)
    axis.set_title('One-month-ahead forecasts on the held-out period')
    axis.set_xlabel('Date')
    axis.set_ylabel('Sea-surface temperature (°C)')
    axis.legend(frameon=False)
    figure.tight_layout()
    figure.savefig(FIGURES_FOLDER / 'test_forecasts.png', dpi=160)
    plt.close(figure)

def write_experiment_notes(series: pd.Series, training_data: pd.DataFrame, test_data: pd.DataFrame, metrics: pd.DataFrame) -> None:
    baseline_score = metrics.loc[metrics['Model'] == 'Naive baseline'].iloc[0]
    ridge_score = metrics.loc[metrics['Model'] == 'Ridge regression'].iloc[0]
    if baseline_score['MAE_C'] == 0:
        mae_change = 0.0
    else:
        mae_change = (baseline_score['MAE_C'] - ridge_score['MAE_C']) / baseline_score['MAE_C'] * 100
    if mae_change > 0:
        summary = f'Ridge regression reduced MAE by {mae_change:.1f}% compared with the naive baseline on these test months.'
    elif mae_change < 0:
        summary = f'Ridge regression had {abs(mae_change):.1f}% higher MAE than the naive baseline on these test months.'
    else:
        summary = 'Both methods had the same MAE on these test months.'
    report = f"# Experiment notes\n\nThese measurements were generated by the latest run of the project.\n\n## Dataset and split\n\nThe dataset contains {len(series)} monthly observations, from\n{series.index.min():%B %Y} through {series.index.max():%B %Y}.\n\nThe first 12 observations are needed to create the longest lag. After that,\n{len(training_data)} rows were used for training and {len(test_data)} rows\nwere held back for testing.\n\n- Training period: {training_data.index.min():%B %Y} to\n  {training_data.index.max():%B %Y}\n- Test period: {test_data.index.min():%B %Y} to\n  {test_data.index.max():%B %Y}\n\n## Forecast methods\n\n**Naive baseline:** the forecast for a month is the observed temperature from\nthe previous month.\n\n**Ridge regression:** the model uses the previous {', '.join(map(str, LAG_MONTHS))}\nmonths of temperature observations, along with the calendar month represented\nby sine and cosine features. The model is a `StandardScaler` and `Ridge`\nregression pipeline.\n\n## Test results\n\n| Method | MAE (°C) | RMSE (°C) |\n|---|---:|---:|\n| Naive baseline | {baseline_score['MAE_C']:.4f} | {baseline_score['RMSE_C']:.4f} |\n| Ridge regression | {ridge_score['MAE_C']:.4f} | {ridge_score['RMSE_C']:.4f} |\n\n{summary}\n\n## What the test means\n\nThis is a rolling one-month-ahead evaluation. The model is fitted once using\nthe training period. During testing, the actual value from an earlier test\nmonth can be used as an input when forecasting the next month. This reflects\na setting where a new observation arrives each month.\n\nThe result is specific to this dataset, the selected test period, the chosen\nfeatures and the fixed Ridge setting. It does not show that this model will\nwork best on other regions, datasets or forecast horizons.\n"
    RESULTS_FOLDER.mkdir(parents=True, exist_ok=True)
    (RESULTS_FOLDER / 'EXPERIMENT_NOTES.md').write_text(report, encoding='utf-8')

def main() -> None:
    RESULTS_FOLDER.mkdir(parents=True, exist_ok=True)
    series = load_monthly_series(DATA_FILE)
    feature_table = make_feature_table(series)
    training_data, test_data = split_by_time(feature_table)
    model = build_forecasting_model()
    model.fit(training_data.loc[:, MODEL_FEATURES], training_data['actual_sst_c'])
    observed = test_data['actual_sst_c'].rename('observed_sst_c')
    baseline = test_data['naive_prediction_c'].rename('naive_prediction_c')
    ridge_forecast = pd.Series(model.predict(test_data.loc[:, MODEL_FEATURES]), index=test_data.index, name='ridge_prediction_c')
    metrics = pd.DataFrame([{'Model': 'Naive baseline', **score_forecast(observed, baseline)}, {'Model': 'Ridge regression', **score_forecast(observed, ridge_forecast)}])
    metrics.to_csv(RESULTS_FOLDER / 'metrics.csv', index=False)
    predictions = pd.concat([observed, baseline, ridge_forecast], axis=1)
    predictions.to_csv(RESULTS_FOLDER / 'test_predictions.csv', index_label='date')
    save_series_plot(series, test_data.index[0])
    save_forecast_plot(observed, baseline, ridge_forecast)
    write_experiment_notes(series, training_data, test_data, metrics)
    print('Forecast comparison finished.\n')
    print(metrics.to_string(index=False, float_format=lambda number: f'{number:.4f}'))
    print(f'\nTraining: {training_data.index.min():%Y-%m} to {training_data.index.max():%Y-%m}')
    print(f'Testing:  {test_data.index.min():%Y-%m} to {test_data.index.max():%Y-%m}')
    print('\nUpdated the figures/ and results/ folders.')
if __name__ == '__main__':
    main()
